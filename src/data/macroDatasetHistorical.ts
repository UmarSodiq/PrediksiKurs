function parseNumber(valStr: string): number {
  if (!valStr) return 0;
  let cleaned = valStr.replace("%", "").trim();
  // If string contains comma, convert comma to dot for standard float parsing
  if (cleaned.includes(",")) {
    cleaned = cleaned.replace(/\./g, "").replace(/,/g, ".");
  }
  const num = parseFloat(cleaned);
  return isNaN(num) ? 0 : num;
}

export function parseMacroDataset(): MacroHistoricalRecord[] {
  const lines = rawMacroCsv.trim().split("\n");
  const records: MacroHistoricalRecord[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line || line.startsWith(";;")) continue;
    const parts = line.split(";");
    if (parts.length >= 9 && parts[0].includes("-")) {
      const date = parts[0].trim();
      const usdIdr = parseNumber(parts[1]);
      const biRate = parseNumber(parts[2]);
      const fedFunds = parseNumber(parts[3]);
      const dxy = parseNumber(parts[4]);
      const brent = parseNumber(parts[5]);
      const neraca = parseNumber(parts[6]);
      const inflasi = parseNumber(parts[7]);
      const reserve = parseNumber(parts[8]);

      if (usdIdr > 0) {
        records.push({
          date,
          usdIdr,
          biRate,
          fedFunds,
          dxy,
          brent,
          neraca,
          inflasi,
          reserve,
        });
      }
    }
  }

  return records.sort((a, b) => a.date.localeCompare(b.date));
}

export const macroHistoricalDataset: MacroHistoricalRecord[] = parseMacroDataset();

/**
 * Calculates Pearson Correlation Coefficient between two numeric series.
 */
export function calculatePearsonCorrelation(x: number[], y: number[]): number {
  const n = Math.min(x.length, y.length);
  if (n < 2) return 0;

  let sumX = 0;
  let sumY = 0;
  let sumXY = 0;
  let sumX2 = 0;
  let sumY2 = 0;

  for (let i = 0; i < n; i++) {
    sumX += x[i];
    sumY += y[i];
    sumXY += x[i] * y[i];
    sumX2 += x[i] * x[i];
    sumY2 += y[i] * y[i];
  }

  const numerator = n * sumXY - sumX * sumY;
  const denominator = Math.sqrt((n * sumX2 - sumX * sumX) * (n * sumY2 - sumY * sumY));

  if (denominator === 0) return 0;
  return Number((numerator / denominator).toFixed(3));
}

